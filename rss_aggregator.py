#!/usr/bin/env python3
"""
Aggregate RSS/Atom feeds listed in a file and serve a combined RSS feed.

Usage:
  /opt/homebrew/bin/python3 rss_aggregator.py --feeds-file rss_feeds.txt --host 127.0.0.1 --port 8090

Endpoints:
  / or /feed or /feed.xml   Combined RSS output
  /health                   JSON status and last refresh metadata

Notes:
    - Source list file format: one URL per line; blank lines and lines starting
        with # are ignored.
    - Source URLs can be RSS, Atom, sitemap urlset XML, or a Shopify Admin
        pseudo-source like shopify-admin://all-blogs.
  - Add ?refresh=1 to /feed.xml to force an immediate refresh.
"""

