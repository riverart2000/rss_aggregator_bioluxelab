DEFAULT_CHANNEL_TITLE = "Aggregated RSS Feed"
DEFAULT_CHANNEL_LINK = "http://localhost/"
DEFAULT_CHANNEL_DESCRIPTION = "Merged feed generated by rss_aggregator.py"
DEFAULT_SHOPIFY_API_VERSION = "2026-01"


